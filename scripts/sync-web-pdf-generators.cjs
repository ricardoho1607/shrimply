let mismatch = false;
Object.entries(outputs).forEach(([filename, content]) => {
  const normalizedContent = content.replace(/[ \t]+$/gm, '');
  const outputPath = path.join(outputDirectory, filename);
  if (checkOnly) {
    if (!fs.existsSync(outputPath) || fs.readFileSync(outputPath, 'utf8') !== normalizedContent) {
      mismatch = true;
      console.error(`${path.relative(root, outputPath)} is not synchronized with the mobile PDF service.`);
    }
    return;
  }
  fs.writeFileSync(outputPath, normalizedContent);
});

