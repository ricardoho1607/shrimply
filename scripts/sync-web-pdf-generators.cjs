const generatedHeader = `// Generated from the canonical mobile PDF services by scripts/sync-web-pdf-generators.cjs.
// Do not edit this file directly.\n`;

const buildGenerator = ({ sourcePath, definitionsStart, logicStart, exportStart, replacements = [], extraImports = '' }) => {
  const source = read(sourcePath);
  let definitions = between(source, definitionsStart, 'const loadBase64Asset');
  let logic = between(source, logicStart, exportStart);
  let output = `${generatedHeader}${pdfI18nImport}${extraImports ? `\n${extraImports}` : ''}\n\n${definitions}\n\n${logic}\n`;
  replacements.forEach(([from, to]) => {
    output = output.replace(from, to);
  });
  return output;
};

