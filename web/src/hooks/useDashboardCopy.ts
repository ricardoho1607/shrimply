const interpolate = (text: string, values?: Record<string, string | number>) => {
  if (!values) return text;
  return Object.entries(values).reduce(
    (result, [key, value]) => result.replaceAll(`{${key}}`, String(value)),
    text,
  );
};

export const getDashboardCopy = (language: Language) => (
  englishText: string,
  values?: Record<string, string | number>,
) => interpolate(language === 'id' ? INDONESIAN_DASHBOARD_COPY[englishText] || englishText : englishText, values);

export const useDashboardCopy = () => {
  const { currentLanguage } = useLanguage();
  return useCallback((
    englishText: string,
    values?: Record<string, string | number>,
  ) => getDashboardCopy(currentLanguage)(englishText, values), [currentLanguage]);
};
